#!/usr/bin/env python3
"""Generate src/unicode_ranges.h: the \\p{L} and \\p{N} codepoint ranges the BPE
pre-tokenizers need (tokenizer.cpp), from Python's unicodedata.

    python3 scripts/gen_unicode_ranges.py > src/unicode_ranges.h

Hugging Face tokenizers matches its pre-tokenizer regexes with the Rust regex
crate's Unicode tables; this reproduces the same general categories (L* and N*)
at the Unicode version Python ships. Whitespace (\\s, the White_Space property)
is small and fixed, so it is written by hand in tokenizer.cpp.
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    print(f"static const uint32_t {name}[][2] = {{")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 6]))
    print("};")


def main():
    cat = lambda cp: unicodedata.category(chr(cp))
    letters = ranges(lambda cp: cat(cp).startswith("L"))
    numbers = ranges(lambda cp: cat(cp).startswith("N"))
    print("// unicode_ranges.h -- GENERATED by scripts/gen_unicode_ranges.py; do not edit.")
    print(f"// Unicode {unicodedata.unidata_version}: general categories L* (letters) and N* (numbers),")
    print("// as inclusive, sorted [first, last] codepoint ranges for binary search.")
    print("#pragma once")
    print("#include <cstdint>")
    print()
    emit("kUnicodeLetterRanges", letters)
    print()
    emit("kUnicodeNumberRanges", numbers)
    print(f"// {len(letters)} letter ranges, {len(numbers)} number ranges", file=sys.stderr)


if __name__ == "__main__":
    main()
